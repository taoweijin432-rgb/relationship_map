import { startPersonQuery, submit, choose, graphView, saved, closeSaved, topic } from './helpers'
import { expect, test, type Page } from '@playwright/test'

test.skip(process.env.RELATIONSHIP_UUID_BROWSER !== '1', '仅显式验证 UUID 物化关系图')

test('UUID 图列表、同专业、来源事实和人物业务编号', async ({ page, request }) => {
  const meta = await request.get('/api/v1/meta')
  expect((await meta.json()).graph_model).toBe('uuid-relations-v5')
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/')
  await startPersonQuery(page)
  await page.getByText('数据与版本', { exact: true }).click()
  await expect(page.getByText(/MySQL 来源 · 图内人物关系/)).toBeVisible()
  await expect(page.getByTestId('person-p:resume:2')).toBeVisible()
  await page.getByTestId('person-p:resume:2').click()
  await expect(page.getByTestId('evidence-card').first()).toContainText('24 个月')
  await expect(page.getByTestId('evidence-card').first()).toContainText('技术总监')
  await choose(page, 'relation-select', '同专业')
  await expect(page.getByTestId('evidence-card').first()).toContainText('同专业')
  await expect(page.getByTestId('evidence-card').first()).toContainText('education_experience')
  await page.getByText('人物编号与来源', { exact: true }).click()
  await expect(page.getByText(/业务编号 [er]0/)).toBeVisible()
  await graphView(page)
  await page.screenshot({ path: test.info().outputPath('uuid-same-major.png'), fullPage: true })
  expect(errors).toEqual([])
})

test('UUID 公司与原始职位必须匹配同条经历，专业专题可查并恢复条件', async ({ page }) => {
  await page.goto('/')
  await startPersonQuery(page)
  await expect(page.getByTestId('person-p:resume:2')).toBeVisible()
  await page.getByRole('button', { name: '按条件找人', exact: true }).click()
  await submit(page)
  await choose(page, 'company-select', '模拟标准公司1 · f4e13bf5-f8ed-57d8-8a7d-d20c850cb445')
  const position = page.getByTestId('position-titles')
  await position.click()
  await position.locator('input').fill('技术总监')
  await page.getByRole('option', { name: '技术总监', exact: true }).click()
  await expect(position).toContainText('技术总监')
  await page.keyboard.press('Escape')
  await submit(page)
  await expect(page.getByTestId('person-p:expert:1')).toBeVisible()
  await expect(page.getByTestId('person-p:resume:7')).toHaveCount(0)
  await topic(page)
  await choose(page, 'topic-kind', '专业')
  await expect(page.getByTestId('entity-topic-card')).toContainText('专业专题')
  await expect(page.locator('.person-row')).not.toHaveCount(0)
  await saved(page)
  await page.getByLabel('条件名称', { exact: true }).fill('UUID专业专题')
  await page.getByRole('button', { name: '保存当前条件', exact: true }).click()
  await closeSaved(page)
  await page.getByRole('button', { name: '按条件找人', exact: true }).click()
  await submit(page)
  await saved(page)
  await page.getByRole('button', { name: '恢复条件 UUID专业专题', exact: true }).click()
  await closeSaved(page)
  await expect(page.getByTestId('entity-topic-card')).toContainText('专业专题')
  await expect(page.getByRole('alert')).toHaveCount(0)
})

