import { expect, test, type Page } from '@playwright/test'
import { advanced, choose, graphView, startPersonQuery, submit } from './helpers'

test.skip(process.env.RELATIONSHIP_NUMERIC_BROWSER !== '1', '显式验证均衡数字来源')

async function selectEntity(page: Page, id: string, label: string) {
  const control = page.getByTestId(id)
  if (id === 'major-select') await advanced(page)
  await expect(control).toBeVisible()
  await control.click()
  await control.getByRole('combobox').fill(label.split(' · ')[0]!)
  const list = await control.getByRole('combobox').getAttribute('aria-controls')
  await page.locator(`[id="${list}"]`).getByRole('option', { name: label, exact: true }).click()
  await page.keyboard.press('Escape')
  await submit(page)
}

test('均衡来源人物、经历证据、同专业与关系画布', async ({ page, request }) => {
  const meta = await (await request.get('/api/v1/meta')).json()
  expect(meta.person_count).toBe(262)
  expect(meta.entity_count).toBe(233)
  expect(meta.graph_model).toBe('numeric-relations-v1')
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await startPersonQuery(page)
  await page.getByText('数据与版本', { exact: true }).click()
  await expect(page.getByText(/SQL 快照 · 图内人物关系/)).toBeVisible()
  await expect(page.locator('.person-row').first()).toBeVisible()
  await page.locator('.person-row').first().click()
  await expect(page.getByTestId('evidence-card').first()).toBeVisible()
  await graphView(page)
  await page.screenshot({ path: test.info().outputPath('balanced-desktop.png'), fullPage: true })
  const person = page.getByTestId('reference-select')
  await person.click()
  await person.getByRole('combobox').fill('梁知远')
  await page.getByRole('option').filter({ hasText: '梁知远' }).click()
  await page.keyboard.press('Escape')
  await choose(page, 'relation-select', '同专业')
  await page.getByRole('button', { name: '人物与经历', exact: true }).click()
  await expect(page.getByTestId('person-p:resume:8')).toBeVisible()
  await page.getByTestId('person-p:resume:8').click()
  await expect(page.getByTestId('evidence-card').first()).toContainText('同专业')
  expect(errors).toEqual([])
})

test('数字学校与专业组合仅匹配同一教育经历', async ({ page, request }) => {
  const school = await (await request.get('/api/v1/entities/school:7')).json()
  const major = await (await request.get('/api/v1/entities/major:8')).json()
  await page.goto('/')
  await page.getByRole('button', { name: '按条件找人', exact: true }).click()
  await selectEntity(page, 'school-select', school.entity.name)
  await selectEntity(page, 'major-select', major.entity.name)
  await expect(page.getByTestId('person-p:resume:9')).toBeVisible()
  await expect(page.getByTestId('person-p:expert:9')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await submit(page)
  await expect(page.getByTestId('person-p:resume:9')).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('balanced-mobile.png'), fullPage: true })
})

test('公司换职链通过中间人物连接并展示逐段证据', async ({ page }) => {
  await page.goto('/')
  await startPersonQuery(page)
  await page.getByTestId('person-p:resume:1').click()
  await page.getByRole('button', { name: '与参考人物对比', exact: true }).click()
  await expect(page.getByTestId('comparison-proof-detail')).toContainText('澜桥软件科技')
  await page.getByRole('button', { name: '经过谁连接', exact: true }).click()
  await selectEntity(page, 'path-right', '周景行 · p:expert:2')
  await expect(page.getByTestId('path-via-p:resume:1')).toBeVisible()
  await page.getByTestId('path-segment-1').click()
  await expect(page.getByTestId('path-proof-detail')).toContainText('远岚信息技术')
  await expect(page.getByTestId('graph-canvas').locator('canvas').first()).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('balanced-path.png'), fullPage: true })
})
