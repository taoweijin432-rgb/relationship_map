from contextlib import AbstractContextManager
from typing import Protocol

from relationship_query.contracts import (
    DatasetCounts,
    FactView,
    PathRequest,
    RelationScope,
    SearchRequest,
)
from relationship_query.domain.graph_relations import GraphProof
from relationship_query.domain.models import Entity, Person
from relationship_query.domain.path_budget import PathBudget


class QueryRepository(Protocol):
    version: str
    reference_month: int

    def person(self, person_id: str) -> Person | None: ...
    def persons(self, ids: list[str]) -> list[Person]: ...
    def entity(self, entity_id: str) -> Entity | None: ...
    def get_entities(self, ids: list[str]) -> list[Entity]: ...
    def search_ids(
        self, request: SearchRequest, reference_id: str | None, after: str | None
    ) -> list[str]: ...
    def matches_person(
        self, request: SearchRequest, reference_id: str, candidate_id: str
    ) -> bool: ...
    def matches_background(self, request: SearchRequest, person_id: str) -> bool: ...
    def fact_views(self, ids: list[str]) -> list[FactView]: ...
    def counts(self) -> DatasetCounts: ...
    def suggest_people(self, keyword: str, limit: int) -> list[Person]: ...
    def suggest_entities(self, kind: str, keyword: str, limit: int) -> list[Entity]: ...


class PathReader(Protocol):
    def persons(self, ids: list[str]) -> dict[str, Person]: ...
    def candidates(self, request: PathRequest) -> list[str]: ...
    def fact_views(self, ids: list[str]) -> list[FactView]: ...
    def fact_views_by_ids(self, ids: list[str]) -> list[FactView]: ...
    def qualify_candidates(self, request: PathRequest, ids: list[str]) -> list[str]: ...


class PathRepository(Protocol):
    version: str
    reference_month: int

    def session(self, budget: PathBudget) -> AbstractContextManager[PathReader]: ...


class GraphRelationReader(Protocol):
    def persons(self, ids: list[str]) -> dict[str, Person]: ...
    def fact_views_by_ids(self, ids: list[str]) -> list[FactView]: ...
    def paths(self, request: PathRequest) -> list[str]: ...
    def proofs(self, request: PathRequest, pairs: list[tuple[str, str]]) -> list[GraphProof]: ...


class GraphRelationRepository(PathRepository, Protocol):
    def graph_session(self, budget: PathBudget) -> AbstractContextManager[GraphRelationReader]: ...


class MaterializedRelationReader(GraphRelationReader, Protocol):
    def shortest_connections(
        self, reference: str, candidates: list[str], request: SearchRequest
    ) -> dict[str, list[str]]: ...

    def read_proofs(
        self, scope: RelationScope, pairs: list[tuple[str, str]], per_kind_limit: int = 1001
    ) -> list[GraphProof]: ...


class MaterializedRelationRepository(Protocol):
    def shortest_connections(
        self, reference: str, candidates: list[str], request: SearchRequest, budget: PathBudget
    ) -> dict[str, list[str]]: ...
    def candidate_session(self, budget: PathBudget) -> AbstractContextManager[None]: ...
    def graph_session(
        self, budget: PathBudget
    ) -> AbstractContextManager[MaterializedRelationReader]: ...
